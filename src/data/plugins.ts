export const ADVANCED_IDS = ['home-assistant', 'discord', 'github'];

export const CATEGORY_ORDER: string[] = [
  'Core System',
  'Models / AI Providers',
  'Productivity',
  'Communication',
  'Developer Tools',
  'Files & Storage',
  'Home / Automation',
  'Research',
];

export function getPluginsByCategory(pluginList: Plugin[]) {
  const grouped: Record<string, Plugin[]> = {};
  for (const cat of CATEGORY_ORDER) {
    const items = pluginList.filter(p => p.category === cat);
    if (items.length > 0) grouped[cat] = items;
  }
  return grouped;
}
